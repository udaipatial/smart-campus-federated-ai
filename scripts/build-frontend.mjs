#!/usr/bin/env node
/**
 * Static frontend build for the Vercel deployment.
 *
 * Copies dashboard/static -> public/ and writes public/config.js with the API
 * base URL taken from the VITE_API_BASE_URL environment variable, so the same
 * source works locally (same-origin) and against a separately hosted backend.
 *
 * No dependencies required; runs on Vercel's default Node runtime.
 */

import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const SOURCE_DIR = resolve('dashboard/static');
const OUTPUT_DIR = resolve('public');

function normalizeApiBaseUrl(raw) {
  const value = (raw || '').trim();
  if (!value) return '';

  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error(
      `VITE_API_BASE_URL is not a valid absolute URL: ${value}\n` +
        'Expected something like https://your-backend-host.example.com'
    );
  }

  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    throw new Error(`VITE_API_BASE_URL must use http(s), received: ${parsed.protocol}`);
  }

  // Trailing slashes would produce double slashes once paths are appended.
  return value.replace(/\/+$/, '');
}

const apiBaseUrl = normalizeApiBaseUrl(process.env.VITE_API_BASE_URL);

await rm(OUTPUT_DIR, { recursive: true, force: true });
await mkdir(OUTPUT_DIR, { recursive: true });
await cp(SOURCE_DIR, OUTPUT_DIR, { recursive: true });

const configSource = `// Generated by scripts/build-frontend.mjs — do not edit.
window.__APP_CONFIG__ = ${JSON.stringify({ apiBaseUrl }, null, 2)};
`;
await writeFile(resolve(OUTPUT_DIR, 'config.js'), configSource, 'utf8');

console.log(
  `Built frontend into public/ (apiBaseUrl: ${apiBaseUrl || 'same-origin'})`
);
